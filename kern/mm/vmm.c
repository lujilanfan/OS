// 分配地址空间描述符。这里只初始化管理信息，调用方可按需提供实际页表。
struct mm_struct *
mm_create(void)
{
    struct mm_struct *mm = kmalloc(sizeof(struct mm_struct));

    if (mm != NULL)
    {
        list_init(&(mm->mmap_list)); // prev、next 都指回表头，表示没有任何 VMA。
        mm->mmap_cache = NULL;
        mm->pgdir = NULL;
        mm->map_count = 0;
        mm->sm_priv = NULL;
    }
    return mm;
}

// 分配 VMA 描述符并设置区间和属性。归属及链表节点由 insert_vma_struct 处理。
struct vma_struct *
vma_create(uintptr_t vm_start, uintptr_t vm_end, uint32_t vm_flags)
{
    struct vma_struct *vma = kmalloc(sizeof(struct vma_struct));

    if (vma != NULL)
    {
        vma->vm_start = vm_start;
        vma->vm_end = vm_end;
        vma->vm_flags = vm_flags;
    }
    return vma;
}

// mm 指定待查的地址空间，addr 是待查的虚拟地址。返回包含 addr 的 VMA，区间为左闭右开。
// 这个查询只检查区间描述，独立于页表是否已建立。mm 为空或地址落在空洞时返回 NULL。
struct vma_struct *
find_vma(struct mm_struct *mm, uintptr_t addr)
{
    struct vma_struct *vma = NULL;
    if (mm != NULL)
    {
        vma = mm->mmap_cache; // 缓存记录上一次成功找到的 VMA。
        if (!(vma != NULL && vma->vm_start <= addr && vma->vm_end > addr))
        {
            // 缓存未命中时从表头线性搜索，le2vma 从内嵌节点取回 VMA 描述符。
            bool found = 0;
            list_entry_t *list = &(mm->mmap_list), *le = list;
            while ((le = list_next(le)) != list)
            {
                vma = le2vma(le, list_link);
                if (vma->vm_start <= addr && addr < vma->vm_end)
                {
                    found = 1;
                    break;
                }
            }
            if (!found)
            {
                vma = NULL;
            }
        }
        if (vma != NULL)
        {
            // 只有成功才更新缓存。查找失败时保留上一次成功的结果。
            mm->mmap_cache = vma;
        }
    }
    return vma;
}

// 有序相邻区间可以相接，prev->vm_end 等于 next->vm_start 时仍无重叠。
static inline void
check_vma_overlap(struct vma_struct *prev, struct vma_struct *next)
{
    assert(prev->vm_start < prev->vm_end);
    assert(prev->vm_end <= next->vm_start);
    assert(next->vm_start < next->vm_end);
}

// 按起始地址插入，让 VMA 指回所属 mm 并增加区间计数。这里只登记区间描述。
void insert_vma_struct(struct mm_struct *mm, struct vma_struct *vma)
{
    assert(vma->vm_start < vma->vm_end);
    list_entry_t *list = &(mm->mmap_list);
    list_entry_t *le_prev = list, *le_next;

    list_entry_t *le = list;
    while ((le = list_next(le)) != list)
    {
        // 停在第一个起始地址更大的 VMA 前。le_prev 指向拟插入位置的前驱。
        struct vma_struct *mmap_prev = le2vma(le, list_link);
        if (mmap_prev->vm_start > vma->vm_start)
        {
            break;
        }
        le_prev = le;
    }

    le_next = list_next(le_prev);

    /* 链表有序，检查插入位置两侧相邻且真实存在的 VMA 即可判断是否重叠。 */
    if (le_prev != list)
    {
        check_vma_overlap(le2vma(le_prev, list_link), vma);
    }
    if (le_next != list)
    {
        check_vma_overlap(vma, le2vma(le_next, list_link));
    }

    vma->vm_mm = mm;
    list_add_after(le_prev, &(vma->list_link));

    mm->map_count++;
}

// 逐个摘下并释放 VMA 描述符，再释放 mm。根页表资源不在此函数中释放。
void mm_destroy(struct mm_struct *mm)
{

    list_entry_t *list = &(mm->mmap_list), *le;
    while ((le = list_next(list)) != list)
    {
        list_del(le);
        kfree(le2vma(le, list_link)); // kfree vma
    }
    kfree(mm); // kfree mm
    mm = NULL;
}

